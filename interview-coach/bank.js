function qbShuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

/* 组题：先把没问过的题用完，再按维度摊开，避免一场全是同一类问题。
   avoid：最近几场用过的题，排在最后。 */
function pickPlan(roundKey, total, avoid) {
  const b = QBANK[roundKey] || QBANK.behavioral;
  const n = Math.max(1, Number(total) || 7);
  const usedRank = {};
  (avoid || []).forEach((q, i) => { usedRank[q] = i; });

  const fresh = qbShuffle(b.q.filter((x) => usedRank[x.q] === undefined));
  const stale = b.q
    .filter((x) => usedRank[x.q] !== undefined)
    .sort((x, y) => usedRank[x.q] - usedRank[y.q]);
  const ordered = fresh.concat(stale);

  const pool = {};
  ordered.forEach((x) => {
    const k = Number(x.d);
    (pool[k] = pool[k] || []).push(x);
  });
  const keys = Object.keys(pool).map(Number).sort((x, y) => x - y);
  const taken = {};
  const out = [];
  const seen = {};
  const cap = Math.ceil(n / Math.max(1, keys.length)) + 1;

  const takeFrom = (k) => {
    while (pool[k].length) {
      const item = pool[k].shift();
      if (seen[item.q]) continue;
      seen[item.q] = 1;
      taken[k] = (taken[k] || 0) + 1;
      out.push({ q: item.q, p: item.p || [], d: item.d });
      return true;
    }
    return false;
  };

  /* 开场先落在第 0 类（动机 / 开场类），别一上来就问边角 */
  if (pool[0] && pool[0].length) takeFrom(0);

  /* 第一轮：每类不超过 cap，优先取剩下多的那一类 */
  let guard = 0;
  while (out.length < n && guard < 200) {
    guard += 1;
    let best = -1;
    let bestScore = -1e9;
    keys.forEach((k) => {
      if (!pool[k].length || (taken[k] || 0) >= cap) return;
      const score = pool[k].length * 10 - (taken[k] || 0) * 8 + Math.random() * 3;
      if (score > bestScore) { bestScore = score; best = k; }
    });
    if (best < 0 || !takeFrom(best)) break;
  }

  /* 第二轮：还没凑够就放开上限 */
  guard = 0;
  while (out.length < n && guard < 200) {
    guard += 1;
    let best = -1;
    let bestLen = 0;
    keys.forEach((k) => {
      if (pool[k].length > bestLen) { bestLen = pool[k].length; best = k; }
    });
    if (best < 0 || !takeFrom(best)) break;
  }

  return out.slice(0, n);
}

function qbTone(roundKey) {
  const b = QBANK[roundKey] || QBANK.behavioral;
  return (b.tone || []).slice();
}

