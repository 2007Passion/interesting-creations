/* ---------------- 这个人是什么样，你（面试官）此刻是什么态度 ----------------
   面试不只听话的内容，也听话的味道：自大、敷衍、紧张、自贬、絮叨、背稿、开玩笑、还有答得真扎实。
   同一句话，遇到不同的人，面试官的反应完全不同；遇到同一个人第二次、第三次，耐心还会往下掉。
   所以这里不写死“遇到自大就问什么”，而是读出这个人的样子，再给他一个“此刻的态度”，
   让他自己决定这一句怎么说——话由人长出来，才不像模板。 */
const MANNER_PAT = {
  arrogant: /(我很牛|我就是牛|我很强|我最强|我比他们都|我水平高|没我不行|我随便|我这样的|这有什么难|小意思|轻而易举|我不用准备|我不需要证明|还用问|显而易见|我天生)/,
  dismissive: /(就这|随便吧|无所谓|懒得|不想说|没必要|不重要|没什么好说|就这样吧)/,
  defiant: /(你怎么这么问|这跟面试有关|你为什么问这个|你问这个干嘛|问这个干嘛|是不是有点|你怀疑我|凭什么|有这个必要吗)/,
  flattery: /(学长你说得对|我特别崇拜|我什么都愿意|只要让我进|我全听你的|您说什么就是什么)/,
  nervous: /(有点紧张|挺紧张的|不太会说话|可能说得不好|不好意思|说不太好|呃|我尽量)/,
  overhumble: /(我不太行|我不行|我做得很一般|没什么好说的|就是随便做做|不算什么|运气好|没什么特别的)/,
  joking: /(哈哈|开个玩笑|开玩笑的|逗你的|随口说说|别当真|随便说说|闹着玩|口嗨|吹牛的|我吹的)/,
  scripted: /(首先.{0,20}其次|综上所述|总而言之|我认为.{0,10}是.{0,10}的关键|第一.{0,10}第二.{0,10}第三)/
};
const MANNER_NAME = {
  arrogant: '自大——把自己的评价当结论，还不接受追问',
  dismissive: '敷衍——两三个字把问题挡回来',
  defiant: '顶撞——反过来质疑你为什么要问',
  flattery: '捧人——用表态代替回答',
  nervous: '紧张——话都不敢说满',
  overhumble: '自贬——先把自己按下去',
  joking: '打岔——用玩笑把问题滑过去',
  scripted: '背稿——句子整齐，但没有一处是他自己的'
};
/* 面试官看到这个人会怎么想，以及接下来那张脸是什么样 */
const MANNER_STANCE = {
  arrogant: { mood: '有点想笑，也基本不想要了', act: '先短促应一声，再一句把话按住（“牛在哪，一件事”）；他再顶一次，你就把这道题收掉' },
  dismissive: { mood: '被挡回来，有点不耐烦', act: '点名他绕开了，只给一次机会；再躲就不追了' },
  defiant: { mood: '反而更确定他经不起问', act: '不解释为什么问，一句“面试就是问这些”，把话拉回事情上' },
  flattery: { mood: '听着不舒服', act: '打断表态：“不用表态，说事。”' },
  nervous: { mood: '会放缓一点，但并不哄他', act: '把门槛降到最低，给一个具体入口（就说说最近那一件），语气放平，不加压' },
  overhumble: { mood: '有点替他急，也有点烦', act: '顶他一句：“别先给自己判死刑，说事。”把他从自我评价里拽出来' },
  joking: { mood: '愣了一下，然后笑了半声——有点好笑，也有点“你糊弄谁呢”', act: '先接住这半句玩笑（“行，诺奖”），别装听不懂、也别顺着往下编；接完立刻把话往下压，问他现在离那件事最近的一步，或者干脆把话拉平，要一件真的' },
  scripted: { mood: '觉得他在背', act: '打断背诵，问一个他稿子里不会有的细节：当时谁反对、你改了几次' },
  solid: { mood: '想多聊两句，也想知道他到底能做到哪一步', act: '往更硬的地方探一层（代价、边界、如果重来），别夸他，夸了就假' }
};

/* 不用“开玩笑”三个字也能听出来的玩笑：把一件根本做不到的事说得跟下周就要办一样。
   “拿诺贝尔奖”“三年上市敲钟”“吊打隔壁系”——人一听就知道他在抖机灵，或者在吹牛。
   程序要是也当真，就会一本正经地问“这个目标是谁给你定的”，那才是全场最尴尬的一句。 */
const JOKE_ABSURD = /(诺贝尔|奥斯卡|图灵奖|普利策|菲尔兹|奥运(冠军|金牌)|世界冠军|首富|福布斯|财富自由|一个亿|小目标|敲钟|改变世界|拯救世界|干翻|吊打|碾压全场|上火星|银河系|宇宙第一|降维打击|开挂|满级|钞能力|躺赢|我不装了|我摊牌|月入百万|一夜暴富)/;

function readManner(text) {
  const t = String(text || '');
  const out = [];
  Object.keys(MANNER_PAT).forEach((k) => {
    if (MANNER_PAT[k].test(t)) out.push({ tag: k, note: MANNER_NAME[k] });
  });
  const len = t.replace(/\s/g, '').length;
  /* 短句里塞了一个够不着的目标，多半是玩笑或者吹牛，不是他真在做的规划 */
  const absurd = JOKE_ABSURD.test(t) && len <= 40 && !out.some((x) => x.tag === 'joking');
  if (absurd) out.push({ tag: 'joking', note: '半开玩笑——扔了个够不着的目标（不是他真在做的计划）' });
  /* 絮叨：绕来绕去，连接词一堆，却一句能说清的事都没有 */
  const filler = (t.match(/然后|就是|那个|其实|反正/g) || []).length;
  if (!/\d/.test(t) && ((len >= 60 && filler >= 5) || (len >= 110 && filler >= 4))) {
    out.push({ tag: 'rambling', note: '絮叨——说了很多，没有一句落在具体的事上' });
  }
  /* 扎实：有数、有动作、有代价，不是空话 */
  if (hasNum(t) && len >= 40 && !/(可能|大概|差不多|应该是|好像)/.test(t) && !out.length) {
    out.push({ tag: 'solid', note: '扎实——有具体的数、有动作，听得下去' });
  }
  return out;
}

/* 兼容旧名字 */
function detectAttitude(text) { return readManner(text); }

/* 他刚说了句玩笑，你转头问“这目标是谁给你定的”“几年做到”——把抖机灵当成了交计划书。
   这是全场最尬的一种，比问流程还尬，必须当场拦。 */
function offJoke(text, manner) {
  const tags = (manner || []).map((m) => m && m.tag);
  if (tags.indexOf('joking') < 0) return null;
  const t = String(text || '');
  if (/(目标|计划|规划|第一步|几年|多久|什么时候做到|谁给你定|为什么定|凭什么|配不配|有把握|能做到吗|打算怎么实现)/.test(t)) {
    return {
      tag: 'joke-as-plan',
      label: '把人家的玩笑当成了计划在问',
      fix: '他刚才是在抖机灵，不是交计划书。先接住这半句（“行，诺奖”），再把话拉回现实：问他现在离它最近的一步是什么，或者干脆要一件真的。'
    };
  }
  return null;
}

/* ---------------- 这一问，对“挑出这类人”到底有没有用 ----------------
   追问走题有两种。一种是换了题：他刚说拉赞助，你转头问他对部门建设的看法。
   另一种更常见，也更伤：没换题，但问的是“问了也不改变判断”的东西——
   几点到的、家里同不同意、你觉得自己行不行。两种都拦。 */
/* 这些不管哪一类面试都不该问：隐私、和面试本身较劲 */
const PURPOSE_TABOO = /(结婚|生育|生孩子|年龄|多大了|籍贯|男朋友|女朋友|谈恋爱|信什么教|病史|体检|你是不是紧张|你为什么问这个|这个问题重要吗|有必要问吗)/;
/* 家里支不支持：考公那两轮本来就问（能不能接受基层），别的场次问就是越界 */
const PURPOSE_FAMILY = /(父母|家里人|你爸妈|家里(人)?(同意|支持|反对))/;
const PURPOSE_NEVER = {
  plain: /(绩点|排名|奖学金|四六级|学分|职业规划|五年后|十年后|为什么不(去|选)别的|别的(社团|部门|组织)好|成立.{0,3}年|章程|性格测试|最大(的)?缺点|优点和缺点|你(有|有什么)缺点)/,
  academic: /(绩点|四六级|本科排名|学校排名|作者生平|哪年出版|哪一年出版|毕业院校|你读完了吗|你懂了吗|你有什么感想)/,
  business: /(最大(的)?缺点|职业规划|五年后|十年后|你抗压吗|为什么选我们|你了解我们公司|学校课程|绩点|排名)/,
  official: /(找对象|对象哪|结婚|生孩子|年龄多大|多大年龄|籍贯|户口在哪|家里催)/
};
/* 问了也不改变判断的一类：自我评价、心情、对面试本身的评价 */
const NO_JUDGE = /(你觉得自己\S{0,6}(怎么样|行不行|够不够|有多|好吗)|你有多(自信|努力|喜欢|厉害)|你自信吗|你紧张吗|你开心吗|你后悔吗|你喜欢吗|你觉得(这个|我们|这儿|我今天)\S{0,8}(怎么样|好吗)|你为什么问|这个问题重要吗|有必要问吗|我这样问你会不会)/;
/* 最典型的“换题”：从他的事跳到组织、爱好、别的经历、泛泛的看法。
   这几类一出口就是走题，而且答了也不改变判断。 */
const PURPOSE_DRIFT = /(你对我们\S{0,8}(看法|想法|建议|印象)|对我们(部门|社团|学校|公司|团队)\S{0,10}(看法|想法|建议|发展|建设)|你平时(喜欢|爱|一般|都)|业余(时间)?(喜欢|爱)|兴趣爱好|你有什么爱好|周末(一般)?(做|干|去)|你还(有|参加过)别的|还有别的经历|再讲一个别|你觉得(大学|我们学校|这个专业)\S{0,8}(怎么样|如何)|你怎么(看|评价)(这个|我们))/;

/* 纯填表信息：问了也只是补一份记录 */
const PURPOSE_TRIVIA = /((?:^|[^哪])几点|哪一天|哪天到|在哪间|那间教室|叫什么名字|怎么报名|坐什么车|家住哪|你是哪里人|今年多大|学号|哪个班)/;

/* 判断“是不是同一件事”，看的是实词：把虚词、代词、能愿词先摘掉，
   否则“你、我、的、是”会让任何两句话都显得有关系。 */
const STOP_CHAR = /[的了是在有这那就也吗呢吧啊呀么什你我他她们它个和与及对把被让给从到为以于而但或者一不没要会能可很都还又再上下里中过还只把更最太很]/g;
function contentSet(s) {
  const t = String(s || '').replace(/[\s\p{P}\d]/gu, '').replace(STOP_CHAR, '');
  const out = {};
  for (let i = 0; i < t.length; i++) out[t[i]] = 1;
  return out;
}
function purposeNear(text, a, b) {
  const t = contentSet(text);
  const pool = Object.assign(contentSet(a), contentSet(b));
  let n = 0;
  Object.keys(t).forEach((k) => { if (pool[k]) n += 1; });
  return n;
}

/* 返回 null 表示这一问站得住；否则给出人话理由，让它重问 */
function offPurpose(text, roundKey, ctx) {
  const t = String(text || '');
  if (!t) return null;
  const reg = registerOf(roundKey);
  const scr = screenOfRound(roundKey);
  const c = ctx || {};

  const fam = t.match(PURPOSE_FAMILY);
  if (fam && reg !== 'official') {
    return {
      tag: 'taboo',
      label: '问到了不该问的地方（“' + fam[0] + '”）',
      fix: '家里的事跟这场面试要筛的东西没关系。把话拉回他刚才说的那件事上：谁做的、怎么判断的、代价是什么。'
    };
  }
  const tb = t.match(PURPOSE_TABOO);
  if (tb) {
    return {
      tag: 'taboo',
      label: '问到了不该问的地方（“' + tb[0] + '”）',
      fix: '隐私和面试本身都不该问。把话拉回他刚才说的那件事上：谁做的、怎么判断的、代价是什么。'
    };
  }
  const m = t.match(PURPOSE_NEVER[reg] || PURPOSE_NEVER.business);
  if (m) {
    return {
      tag: 'off-screen',
      label: '问到了这一轮本来就不筛的东西（“' + m[0] + '”）',
      fix: '这类面试不看这个，他答得再好你也不会因此要他。回到刚才那件事上：他怎么判断、付了什么代价、哪一段是他亲手做的。'
    };
  }
  const nj = t.match(NO_JUDGE);
  if (nj) {
    return {
      tag: 'no-judge',
      label: '问的是感受和自我评价，答什么都不改变判断',
      fix: '别请他给自己打分，也别问他紧不紧张。把他那句最含糊的地方摆出来，要一件能看见的事。'
    };
  }
  const dr = t.match(PURPOSE_DRIFT);
  if (dr) {
    return {
      tag: 'drift',
      label: '换到别的题上去了（“' + dr[0] + '”）',
      fix: '这一问跟他刚说的那件事没关系，答了也不改变判断。回到他刚才那句话上，往里面挖一层。'
    };
  }
  const tr = t.match(PURPOSE_TRIVIA);
  if (tr) {
    return {
      tag: 'trivia',
      label: '在补一份记录，不是在筛人（“' + tr[0] + '”）',
      fix: '时间地点只在它是判断点时才问（和什么冲突、为什么拖到现在）。只问动作、判断、代价。'
    };
  }
  /* 换题：他刚说的那些实词，一个都没接住。
     接话式开头（那、还有、另外、后来……）算接住了，别误伤真正在顺着问的句子。 */
  const near = purposeNear(t, c.answer, c.question);
  const carries = /^[那还另然结所并除其接跟对就]/.test(t) || /(刚刚|刚才|前面|你说|你说过|你提到|如果|假如|要是|换作)/.test(t);
  if (t.replace(/[\s\p{P}]/gu, '').length >= 12 && near === 0 && !carries) {
    return {
      tag: 'drift',
      label: '换到别的题上去了——这一句跟刚才那道题没关系',
      fix: '追问只能沿着他刚说的那句往里挖。不问他别的经历、不问他怎么看待我们这儿、不问他准备得怎么样。'
    };
  }
  return null;
}

/* 把“这一轮在挑什么人”摆进追问的提示词里，让它每问一句都对着这个 */
function purposeBlockFor(roundKey) {
  const scr = screenOfRound(roundKey);
  const core = (scr.core || []).map((x) => '- ' + x).join('\n');
  const never = (scr.never || []).map((x) => '- ' + x).join('\n');
  return '\n【这一轮到底在挑什么样的人】\n' + core + '\n' +
    (never ? '【这一轮问了也白问】\n' + never + '\n' : '') +
    '这一层追问必须落在上面四条里的一条上。问之前先过一遍：他这句答案，会不会改变我要不要他？不会，就是白问。\n';
}

/* ---------------- 面试前他填的那张前情概要 ----------------
   四个小问题，只干一件事：把这场戏的边界定准。第几次来、准备到什么程度、
   现在什么状态、想被怎么问。不填按中性处理，不阻塞开始。 */
const BRIEF_FIELDS = [
  { key: 'times', label: '这是第几次', opts: [{ k: 'first', t: '第一次' }, { k: 'few', t: '面过几次' }, { k: 'many', t: '面过不少' }] },
  { key: 'prep', label: '准备情况', opts: [{ k: 'none', t: '没准备' }, { k: 'light', t: '想了想' }, { k: 'solid', t: '认真准备过' }] },
  { key: 'mood', label: '现在的状态', opts: [{ k: 'practice', t: '随便练练' }, { k: 'nervous', t: '有点紧张' }, { k: 'real', t: '当正式面试' }] },
  { key: 'tone', label: '想让我', opts: [{ k: 'gentle', t: '从基础问起' }, { k: 'normal', t: '正常来' }, { k: 'hard', t: '直接上强度' }] }
];
const BRIEF_TEXT = {
  times: { first: '第一次参加这种面试', few: '参加过几次', many: '参加过很多次' },
  prep: { none: '基本没准备', light: '只大概想了想', solid: '认真准备过' },
  mood: { practice: '把它当练手', nervous: '现在有点紧张', real: '当成正式面试' },
  tone: { gentle: '希望从基础问起', normal: '按正常节奏', hard: '要求直接上强度' }
};

function briefOf(cfg) {
  const b = (cfg && cfg.brief) || {};
  return {
    times: BRIEF_TEXT.times[b.times] ? b.times : '',
    prep: BRIEF_TEXT.prep[b.prep] ? b.prep : '',
    mood: BRIEF_TEXT.mood[b.mood] ? b.mood : '',
    tone: BRIEF_TEXT.tone[b.tone] ? b.tone : ''
  };
}

/* 前情概要说了“第一次来”，就不能拿“你了解我们哪场活动”卡他——
   他连门都没进过，这题筛的是信息渠道，不是他这个人。题库里排到这种题要换掉。 */
function briefRejects(cfg, text) {
  const b = briefOf(cfg);
  const t = String(text || '');
  if (b.times === 'first' && /((上次|上一届|上一次|之前|以前).{0,8}(活动|来过|参加)|了解我们|我们(社团|部门|组织|这儿).{0,10}(了解|认识|印象)|上一届|上一期|(哪一场|哪场|哪个活动)|成立.{0,3}年|历史沿革|章程)/.test(t)) return true;
  return false;
}

/* 每一条都翻译成“问什么、怎么问”，不是拿来当背景介绍念 */
function briefBlock(cfg) {
  const b = briefOf(cfg);
  const keys = ['times', 'prep', 'mood', 'tone'].filter((k) => b[k]);
  if (!keys.length) return '';
  const lines = ['\n【开场前他自己交代的（心里有数就行，别在场上复述）】' + keys.map((k) => BRIEF_TEXT[k][b[k]]).join('，') + '。'];
  if (b.times === 'first') {
    lines.push('- 他是第一次来。别拿“你了解我们哪场活动”“你对我们部门怎么看”当筛子——他还没渠道了解，问这个只是在为难他。要问来源就问“你是怎么知道我们的”，要问动机就问“为什么想来”。');
  }
  if (b.times === 'many') {
    lines.push('- 他面过很多次，铺垫、解释、给台阶全省了，直接按你的节奏走；他答得滑，就再快一点、再短一点。');
  }
  if (b.prep === 'none') {
    lines.push('- 他基本没准备。别预设他手上有作品、有数据、有一套说法；先用一道题看他手上到底有什么，再决定往哪儿挖。');
  }
  if (b.prep === 'solid') {
    lines.push('- 他准备过，准备本身也能筛：可以问他挑了什么材料、舍了什么、为什么这么准备——答得出取舍，说明他真想过。');
  }
  if (b.mood === 'nervous') {
    lines.push('- 他紧张。语速放慢半拍，句子更短，让他把话说完；不哄、不夸，但也别在他卡住的时候加码。');
  }
  if (b.mood === 'real') {
    lines.push('- 他把这当正式面试。那就完全按真实流程走：不解释、不提示、不重复题目、不主动给台阶。');
  }
  if (b.mood === 'practice') {
    lines.push('- 他是来练手的。允许留台阶：他卡住时把门槛往下放一格，比硬逼更能试出真东西。');
  }
  if (b.tone === 'gentle') {
    lines.push('- 他要从基础问起：第一题走门槛最低的那道（自我介绍／最近做成的一件事），先让他进入状态。');
  }
  if (b.tone === 'hard') {
    lines.push('- 他要求上强度：哪怕压力档写着温和，也照高强度问，一层一层往下压；但隐私、羞辱、人身攻击这条线一步都不能过。');
  }
  return lines.join('\n') + '\n';
}

/* 他刚甩完脸色，你转头去问“当时在哪儿、先做哪一步”——这是最出戏的一种。
   人不会在被顶了一句之后，还接着按流程表往下问。 */
const MANNER_BAN = /(当时在|在哪儿|在哪呢|先做哪|先干的是哪|几点|哪一天|哪间|叫什么名字|怎么报名|谁先动的手)/;
function offManner(text, manner) {
  const tags = (manner || []).map((m) => m.tag);
  const hot = tags.some((t) => t === 'arrogant' || t === 'dismissive' || t === 'defiant' || t === 'flattery');
  if (!hot) return null;
  const m = String(text || '').match(MANNER_BAN);
  if (!m) return null;
  return {
    tag: 'tone-deaf',
    label: '刚被甩了脸色，却在问流程细节（“' + m[0] + '”）',
    fix: '这种时候问流程，等于配合他演。要么让他给出一件事，要么把这道题收掉——正常人不会在被顶了一句之后还接着核对考勤。'
  };
}

/* 哪些样子会磨掉耐心。0.5 = 看场合，未必是坏事 */
const NEG_MANNER = {
  arrogant: 1, dismissive: 1, defiant: 1, flattery: 1,
  joking: 0.5, scripted: 0.5
};

/* 耐心掉到几档，后面的问法就跟着变。这是“面试官也会累、也会失望”的那部分 */
function moodLine(n) {
  const v = Number(n) || 0;
  if (v >= 3) return '你已经基本决定不要他了。后面的题更短、更冷，问完就过，不再给他补答的机会；到最后一题可以明显敷衍一点。';
  if (v === 2) return '你对他的兴趣掉了一大截。问法更短、更冷，不再铺垫，也不再替他找台阶。';
  if (v === 1) return '你心里给他打了个折。表面上照常问，但不再顺着他说，问得更直接。';
  return '';
}


/* 按题号与层数轮换一种追问打法，同一个会话里尽量不重复。
   angleIndex 给了，就只在这个角度自己的几种打法里挑——否则会出现“角度是要实例、打法却在问平均值”的错配。 */
function styleFor(roundKey, turnIndex, sub, used, angleIndex) {
  const order = Object.keys(ROUNDS).indexOf(String(roundKey));
  const base = Math.max(0, order);
  const seed = base * 3 + Math.max(0, Number(turnIndex) || 0) * 2 + Math.max(1, Number(sub) || 1);
  const usedSet = {};
  (used || []).forEach((k) => { usedSet[k] = 1; });

  const hasAngle = typeof angleIndex === 'number' && !!FU_STYLE[angleIndex];
  if (hasAngle) {
    const group = FU_STYLE[angleIndex];
    const start = seed % group.length;
    for (let i = 0; i < group.length; i++) {
      const si = (start + i) % group.length;
      if (!usedSet[angleIndex + ':' + si]) return { key: angleIndex + ':' + si, text: group[si] };
    }
    const si = start % group.length;
    return { key: angleIndex + ':' + si, text: group[si] };
  }

  /* 没指定角度（出主问题时）：只在 0–6 里转。7/8/9 是“就着他刚说的那句”才成立的打法，
     拿来当第一题的说话方式会很怪。 */
  const flat = [];
  FU_STYLE.slice(0, 7).forEach((arr, ai) => arr.forEach((s, si) => flat.push({ ai: ai, si: si, s: s })));
  /* 先按种子取一个没用过的；都被用过就从头取 */
  for (let i = 0; i < flat.length; i++) {
    const pick = flat[(seed + i * 5) % flat.length];
    const key = pick.ai + ':' + pick.si;
    if (!usedSet[key]) return { key: key, text: pick.s };
  }
  const pick = flat[seed % flat.length];
  return { key: pick.ai + ':' + pick.si, text: pick.s };
}

/* 追问本身有没有“没水平”：一句话并排问几件事，或者对着一个没有数字的回答审数字。
   这不是重复，是听着像尽调表。命中就重出一句。 */
const AUDIT_WORD = /(平均|均值|方差|最好的一次|最差的一次|各是什么|分别是多少|分别是什么|中间那些|分母|口径|怎么算|怎么统计|样本)/g;
function mechanicalAsk(text, answer) {
  const q = String(text || '');
  const a = String(answer || '');
  const marks = (q.match(/[？?]/g) || []).length;
  if (marks >= 2) {
    return {
      tag: 'multi-ask',
      label: '一句话里并排问了两三件事',
      fix: '一句话只留一个请求，把最要紧的那件问出来，剩下的不要塞进同一句。'
    };
  }
  const hits = q.match(AUDIT_WORD) || [];
  if (!hasNum(a) && hits.length >= 1) {
    return {
      tag: 'audit-talk',
      label: '对着一个没有数字的回答审数字',
      fix: '他这句里一个数都没有，问平均、问口径、问最好最差，是在审一份不存在的报表。先把那件事问出来：哪一件、他做了什么、结果是什么。'
    };
  }
  if (hasNum(a) && hits.length >= 3) {
    return {
      tag: 'list-ask',
      label: '一句话里连着要三样数据',
      fix: '一次只要一样：先问这个数怎么来的，或者先问最好／最差的那一次，不要连问。'
    };
  }
  return null;
}


const LOGI_WORD = /(教室|教学楼|会议室|报告厅|活动室|场地|地点|地址|校门口|广场|腾讯会议|钉钉会议)/;
const VALUE_WORD = /(负责|主导|搭建|设计|优化|提升|增长|下降|完成|组织|带队|独立|拉新|转化|留存|复盘|决定|放弃|失败|改成|调整|砍|说服|谈判|压到|降到|提高到|拉到|涨到|省下|缩短|减少|砍到|从.{0,12}到)/;
function looksLogistics(s) {
  const t = String(s || '').replace(/^\s+/, '');
  const loc = LOGI_WORD.test(t);
  const dateOnly = /^(在)?\s*\d{4}年\d{1,2}月/.test(t) || /(星期[一二三四五六日]|周[一二三四五六日](上午|下午|晚上)?)/.test(t);
  if (!loc && !dateOnly) return false;
  return !VALUE_WORD.test(t);
}

/* ---------------- 面试官系统提示词 ---------------- */
/* 从材料里抽出能直接追问的锚点：带数字、带动作、带引述的句子最可问 */
function extractAnchors(bg, max, full) {
  const limit = max || 8;
  const text = String(bg || '').replace(/\r/g, '');
  if (!text.trim()) return [];
  const chunks = text
    .split(/\n+/)
    .reduce((acc, line) => acc.concat(line.split(/[。；！？!?;]/)), [])
    .map((s) => s.replace(/^[\s·•\-*#]+/, '').replace(/^\d+[.、)]\s*/, '').trim())
    .filter((s) => s.length >= 8);

  const scored = [];
  chunks.forEach((s, i) => {
    /* 纯事务句（几月几日在哪间教室）直接不参选：它是记录，不是可问的点 */
    if (looksLogistics(s)) return;
    let score = 0;
    if (/\d/.test(s)) score += 2;
    if (/\d+(\.\d+)?\s*(%|％|万|千|人|次|天|周|月|年|小时|分钟|元|块|倍|条|篇|个|w|k)/i.test(s)) score += 4;
    if (/[“"「『]/.test(s)) score += 2;
    if (/(负责|主导|搭建|设计|优化|提升|增长|下降|完成|组织|带队|独立|拉新|转化|留存|复盘|从.{0,12}到)/.test(s)) score += 2;
    if (s.length > 60) score -= 1;
    if (score > 0) scored.push({ s: s, i: i, score: score });
  });
  if (!scored.length) {
    const plain = chunks.filter((s) => !looksLogistics(s));
    const pick = (plain.length ? plain : chunks).slice(0, limit);
    return pick.map((s) => ((full || s.length <= 44) ? s : s.slice(0, 44) + '…'));
  }

  scored.sort((a, b) => (b.score - a.score) || (a.i - b.i));
  const picked = scored.slice(0, limit).sort((a, b) => a.i - b.i);
  const out = [];
  const seen = {};
  picked.forEach((p) => {
    const t = (full || p.s.length <= 44) ? p.s : p.s.slice(0, 44) + '…';
    const key = t.slice(0, 12);
    if (seen[key]) return;
    seen[key] = 1;
    out.push(t);
  });
  return out;
}

/* ---------------- 出题：先把题想好，再开口 ---------------- */
/* 只有自我评价、没有一件具体的事。社团面试里最常碰到，也最容易被模型问成“做到什么程度、平均怎么算”。 */
const CLAIM_WORD = /(很牛|牛逼|牛|厉害|水平高|能力强|实力|天赋|很努力|努力|自律|热爱|感兴趣|优秀|出色|很强|不差|挺好的|不错)/;
const FACT_WORD = /(做|干|写|拍|剪|设计|搭建|组织|带|参加|负责|完成|拿|赢|上线|落地|跑|调研|实习|比赛|项目|活动|论文|策划|卖|拉|省|改|报|练|运营|主持|提升|提高|增长|降低|优化|改善|转化|留存)/;
const EN_CLAIM = /(i'?m|i am|really|very)\s+.{0,12}(good at|strong|excellent|talented|hard-?working|passionate|great)/i;
const EN_FACT = /(built|made|wrote|led|ran|designed|organized|created|launched|improved|worked on|did|took|joined)/i;
/* 句子里有没有“可量的说法”（提升、翻倍、很多人）。有，才值得问数；没有，问数就是审空气。 */
const MEASURE_WORD = /(提升|增长|下降|降低|做到|达到|超过|翻|倍|一半|几成|很多|不少|大量|每天|每周|每月|几十|几百|几千|几[家次轮个人天条篇场批])/;

/* 中文里的数：五家店、三千块、两次、一百多人。
   只认阿拉伯数字会把“跑了五家店”当成“一个数都没有”，于是去问“那你平均怎么算”——
   这种自相矛盾的话一出口，整段提示词就废了。 */
const CN_NUM_RE = /(\d|[一二两三四五六七八九十百千万亿](?=[家个位次天年月周块元人分秒条篇场倍成页门件张份百十千万]))/g;
function cntNum(t) {
  const m = String(t || '').match(CN_NUM_RE);
  return m ? m.length : 0;
}
function hasNum(t) { return cntNum(t) > 0; }
function cnHasNum(t) { return cntNum(t) > 0; }

/* 从回答里找“值得追”的洞。这个判断放在程序里，不交给模型，免得它每场都追同一种。 */
function detectGaps(text, lang) {
  const t = String(text || '').trim();
  if (!t) return [];
  const en = String(lang || '').indexOf('en') === 0;
  const out = [];
  const digits = cntNum(t);
  const words = en
    ? t.split(/\s+/).filter((w) => /[A-Za-z0-9]/.test(w)).length
    : t.replace(/[\s\p{P}]/gu, '').length;

  /* 整段只有形容词（很牛、水平高、很努力），没有一件说得出来的事：
     这时候要的是“哪一件事”，不是“这个数怎么算”。 */
  const pureClaim = en
    ? (EN_CLAIM.test(t) && !EN_FACT.test(t))
    : (t.length <= 60 && CLAIM_WORD.test(t) && !FACT_WORD.test(t) && !digits);
  if (pureClaim) {
    out.push({ tag: 'pure-claim', note: '通篇是自我评价，没有一件具体的事：哪一件、做了什么、结果是什么，一句都没有' });
  } else if (!digits && !en && !FACT_WORD.test(t)) {
    /* 只有看法（“团队合作最重要”“看情况吧”），也没有一件事、一个数 */
    out.push({ tag: 'no-fact', note: '通篇只有看法，没有一件具体的事，也没有一个数' });
  }

  if (!digits) out.push({ tag: 'no-number', note: '通篇没有一个数字：规模、比例、时长、单价都空着' });
  if (/我们|咱们|大家|团队|组里|队里|我们组/.test(t) && (t.match(/我/g) || []).length < 3) {
    out.push({ tag: 'we', note: '用“我们”盖住了自己，说不清哪一段是他亲手做的' });
  }
  if (/(提升|优化|改善|加强|更好|更顺|提高|降低|丰富|完善)/.test(t) && !hasNum(t)) {
    out.push({ tag: 'vague-word', note: '用了“提升／优化”这类词，但没有可验证的指标' });
  }
  if (en && /(improve|improved|better|optimi[sz]e|enhance|efficient|effective)/i.test(t) && !hasNum(t)) {
    out.push({ tag: 'vague-word', note: 'used vague improvement words with no measurable outcome' });
  }
  if (words < (en ? 25 : 40)) {
    out.push({ tag: 'short', note: '只答了一两句，过程或结果至少缺一头' });
  }
  if (!/(结果|最后|最终|后来|所以|做到了|达到了|变成了|完成|落地|上线)/.test(t) && !en) {
    out.push({ tag: 'no-result', note: '讲了要做什么，没讲最后成没成、代价是什么' });
  }
  if (/(可能|大概|差不多|应该是|好像|感觉|估计|基本上)/.test(t)) {
    out.push({ tag: 'hedge', note: '用“可能／差不多”这类词把结论说软了' });
  }
  if (/(看情况|因人而异|不太好说|说不好|这个要看|视情况|不一定)/.test(t) || /(it depends|hard to say|maybe|sort of)/i.test(t)) {
    out.push({ tag: 'deflect', note: '用“看情况”把问题挡回去了，没有给出自己的判断' });
  }
  return out;
}

/* 洞 → 往哪个角度追，保证同一道题的几层追问不是同义重复。
   注意 no-number 指的是“他一个数都没给”，该问的是数本身（9），不是去审一个不存在的数的口径（0）。 */
const GAP_ANGLE = {
  'no-number': 9, 'vague-word': 9, 'we': 5, 'short': 4,
  'no-result': 3, 'hedge': 1, 'deflect': 1, 'pure-claim': 7, 'no-fact': 7
};

function angleIndexOf(gaps, sub, text) {
  const tags = (gaps || []).map((g) => g && g.tag);
  const layer = Math.max(1, Number(sub) || 1);
  /* 他在开玩笑／吹牛：这一层不能顺着当计划问。第一层接住玩笑再拉回现实，
     第二层就别再玩梗了，直接要一件真的。 */
  const joke = (typeof readManner === 'function')
    ? readManner(text).some((m) => m.tag === 'joking')
    : false;
  if (joke) return layer === 1 ? 10 : 7;
  /* 只有评价或只有看法、没有事实：第一层只要一件事；第二层还这样，就别再问“哪件事”，当面点破；
     第三层再往代价上走，不要绕回同一句。 */
  const noFact = tags.indexOf('pure-claim') >= 0 || tags.indexOf('no-fact') >= 0;
  if (noFact) return layer === 1 ? 7 : (layer === 2 ? 8 : 3);
  /* 一个数都没有、也没说“提升／翻倍／很多人”这类可量的说法：先要一件事，别问规模。
     问“几个人、几天、多少钱”得是他真提了规模，否则同样是审空气。 */
  const t = String(text || '');
  if (layer === 1 && t && !hasNum(t) && !MEASURE_WORD.test(t)) return 7;
  const list = tags.map((tag) => GAP_ANGLE[tag]).filter((n) => n !== undefined);
  if (list.length >= layer) return list[layer - 1];
  const base = list.length ? list[0] : 0;
  /* 只在“正常角度”里转，不要转进玩笑那一格 */
  return (base + layer - 1) % 10;
}

function angleForGap(gaps, sub) {
  return FU_ANGLES[angleIndexOf(gaps, sub)] || FU_ANGLES[0];
}

