/* ---------------- 开场 ---------------- */
function openingUserMessage(cfg) {
  const r = ROUNDS[cfg.round] || ROUNDS.behavioral;
  if (r.lang === 'en') return '（The session is starting. Follow the directive and open in English.）';
  return '（候选人已就坐。请按本轮指令开场，直接问第一个问题。）';
}

