/* 先过通用筛子，再过这一轮的筛子。返回 null = 值得问。 */
function screenValueOf(text, roundKey) {
  const bad = askValueOf(text);
  if (bad) return bad;
  const re = ROUND_NEVER_PAT[roundKey];
  if (re && re.test(String(text || ''))) {
    return {
      tag: 'off-round',
      label: '这一轮问了也白问的问题',
      fix: '这类问题在' + ((ROUNDS[roundKey] || {}).label || '这一轮') + '里问不出判断，也不会影响录取决定。换成本轮真正在筛的那件事（见【这一类面试真正在筛什么】）。'
    };
  }
  return null;
}

/* 这句问法是不是又落回了模板。用来防“每道题都问这个数谁测的”。 */
function templateAsk(text) {
  const q = String(text || '');
  for (let i = 0; i < TEMPLATE_ASKS.length; i++) {
    if (TEMPLATE_ASKS[i].re.test(q)) return TEMPLATE_ASKS[i].tag;
  }
  return '';
}

/* ---------------- 场合用词 ----------------
   同一个意思，在不同场合该用完全不同的词。学长不会说“基线”“样本”，
   论文答辩里这些反而是本行话。这里按轮次定一套，命中就重说。 */
const ROUND_REGISTER = {
  club: 'plain', studentorg: 'plain',
  academic_en: 'plain', class_en: 'plain', class_discuss: 'plain',
  grad: 'academic', seminar: 'academic', defense: 'academic',
  civil: 'official', civil_talk: 'official',
  intern: 'business', bigtech: 'business', behavioral: 'business',
  technical: 'business', case: 'business', negotiation: 'business'
};
const REGISTER_NAME = {
  plain: '大白话', business: '职场话', academic: '学术话', official: '公家话'
};
/* 只有“大白话”场合禁这些：它们是评估表、尽调报告的词，不是人和人聊天的词 */
const JARGON = /(基线|样本量|样本|口径|指标|数据来源|量化|可量化|归因|维度|闭环|抓手|赋能|颗粒度|对齐|迭代|验证体系)/;

function registerOf(roundKey) {
  return ROUND_REGISTER[roundKey] || 'business';
}

function offRegister(text, roundKey) {
  const t = String(text || '');
  if (registerOf(roundKey) !== 'plain') return null;
  const m = t.match(JARGON);
  if (!m) return null;
  return {
    tag: 'jargon',
    word: m[0],
    label: '用了不属于这个场合的词（“' + m[0] + '”）',
    fix: '你是在跟一个大一学生聊社团，不是在写评估报告。“' + m[0] + '”这种词一出口就不像学长。换成人话：几个人、几次、多少钱、这个数是怎么数出来的、有没有人没算进去。'
  };
}

