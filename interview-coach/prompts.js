function buildScoringPrompt(cfg, turns) {
  const r = ROUNDS[cfg.round] || ROUNDS.behavioral;
  const p = PRESSURES[cfg.pressure] || PRESSURES.standard;
  const scene = sceneOfRound(cfg.round);
  const dims = dimsOfRound(cfg.round);
  const en = r.lang === 'en';
  const dimBlock = dims.map((d, i) => {
    return `${i + 1}. ${d.key}：${d.desc}
   1分=${d.anchors[1]}；3分=${d.anchors[3]}；5分=${d.anchors[5]}`;
  }).join('\n');

  const transcript = turns.map((t) => {
    const layer = t.sub ? '·追问' + t.sub : '';
    if (t.role === 'interviewer') return `面试官（第${t.qIndex}题${layer}）：${t.text}`;
    const tag = [];
    if (t.skipped) tag.push('未作答');
    if (t.spent) tag.push('用时' + t.spent + '秒');
    if (t.via === 'voice' && t.seconds) tag.push('语音转写' + t.seconds + '秒');
    return `候选人（第${t.qIndex}题${layer}作答）${tag.length ? '（' + tag.join('，') + '）' : ''}：${t.text}`;
  }).join('\n\n');

  const mainQs = turns.filter((t) => t.role === 'interviewer' && !t.sub).length;
  const fuTotal = turns.filter((t) => t.role === 'interviewer' && t.sub).length;
  const keys = dims.map((d) => d.key).join('、');
  const langNote = en
    ? '\n- 候选人原话是英文，evidence 保留英文原样，不要翻译。所有评语、诊断、示范改法仍用中文；改写建议（rewrite）与示范句里的英文要地道，别写成中式英语。\n'
    : '';

  const sp = cfg.speech || null;
  const unit = en ? '词' : '字';
  const speechNote = sp && sp.spoken
    ? `\n【口语信息】本场有 ${sp.spoken} / ${sp.total} 题是语音作答${sp.rate ? '，平均语速约 ' + sp.rate + ' ' + unit + '/分钟' : ''}${sp.conf ? '，语音识别置信度均值 ' + sp.conf + '（0–1）' : ''}。\n- 文本层面的问题（停顿、重复、口头禅、自我打断、句子没说完、中文夹进英文）都算得进去。\n- 语速可以评：明显偏慢（大量停顿、反复重来）或偏快（吞字、句子挤在一起）都要点出来。\n- ${en ? '发音只能靠识别置信度间接判断：置信度低说明机器听不清，通常意味着吞音、连读糊或重音位置不对。' : '发音只能靠识别置信度间接判断。'}可以提示“可能存在的发音问题”，但不要断言音色、音量、语调这些你拿不到的东西。\n- 纯打字作答的题，不要评价任何口语特征。\n`
    : '';

  const timeNote = cfg.mode === 'real'
    ? `\n【限时实战】本场是实战模式，每题限时 ${cfg.limit || 90} 秒，超时会被自动收走。\n- 某题用时接近或超过限时、答案明显断在半句，要在 diagnosis 里直接点出“时间分配”问题，并说明该砍哪一段。\n- 不要因为限时降低 rubric 标准。\n`
    : '';

  const fuNote = fuTotal
    ? `\n【追问怎么算分】这一场一共追问了 ${fuTotal} 次，追问和它的回答都是这道题的一部分。\n- questions[].score 是这道题连同它所有追问的综合分；追问里补出的具体证据可以往上给，追问里暴露的回避、前后矛盾、临时改口要往下压。\n- 被追问后仍然只重复原话、把问题丢回来、越说越虚，这一题不能超过 3 分。\n- questions[].fu 逐层记下追问要了什么、他给了什么、这一层暴露了什么；没有追问的题 fu 给空数组。\n`
    : '';

  const langExtra = en
    ? `\n【这一轮额外的两项】
- 「英语语言质量」只看文本：语法、时态、单复数、冠词介词、动词搭配、句子完整性、用词是否准确，以及有没有把中文逐字翻过去。
- 「口语与发音」只在有语音作答时评；整场都是打字，score 填 null，comment 写“本轮未涉及”。
- 这两项和内容分开打：内容答得好但语言稀烂，语言项照样低分；语言漂亮但内容空，内容项低分。\n`
    : '';

  return `你是资深面试评估专家，正在给一场「${scene.label} · ${r.label}」打分。对象：${cfg.job}。压力档：${p.label}。
这场面试的形态：${r.tagline}。

【rubric】每项 1–5 分，5 最好：
${dimBlock}
${langExtra}
【评分纪律】
- 严格。空话、无出处数字、把团队成果说成个人成果、回避追问 → 该项不高于 2 分。
- comment 必须指向具体的一句原话或一个缺失，禁止“表现不错”“有待提高”这类空评。
- evidence 必须是候选人的原话短引（不超过 30 字）；实在没有就写“（未提供）”。
- rewrite 要写成候选人能直接照着说的一句话，具体、有数字或细节，不要说“应该更具体”。
- model_answer 是这道题的参考回答：第一人称、口语、能直接背下来练，120–200 字，必须以一个具体证据或数字撑住；中文轮用中文，英文轮用英文。只写“该怎么答”，不要点评候选人。若候选人本身答得很好，也照样给一份更完整的版本。
- 参考回答要像真人在面试现场说的话：用得上行业里的具体名词（哪个渠道、什么工具、哪个环节、谁拍的板），允许口语（“说实话”“当时我就觉得不对”），允许一句自我修正。要做到念出来不别扭。
- 参考回答里必须有一处取舍或代价（放弃了什么、哪里没做好、代价是多少），只讲成绩的答案不算好答案。
- 不许出现这些词：首先、其次、最后、综上、总而言之、赋能、抓手、闭环、颗粒度、打法、组合拳。也不要用“我做了三件事”这种三段式开头。
- 不同题目的参考回答句式必须不一样：有的从结论开头，有的从场景开头，有的从一句反问或自我质疑开头。连着两题用同一个开头就是失败。
- 参考回答里可以出现行业里真实存在的做法和术语（比如封面标题前三秒、抽样口径、对照班、AB 分流），但不要编造具体公司名、具体金额和别人拿不到的数据；拿不准就写自己做过的那部分。
- comment 和 diagnosis 要像真人面试官当场说的话，宁可粗一点：不要用“表达流畅”“逻辑清晰”“整体不错”“有待提升”“建议加强”这类评语，也不要每道题都用同一种句式开头。
- 如果整场对话完全没有触及某个维度（没问到、对方也没提到），score 填 null，comment 写“本轮未涉及”，不要因为没问到就压成 1 分。
- 5 分只在明显优于一般候选人时给。${langNote}
${fuNote}${speechNote}${timeNote}【对话记录】
${transcript}

【输出要求】
只输出一个 JSON 对象，不要任何解释、不要 markdown 代码块。所有文字用中文（英文原话除外）。
{
  "verdict": "不超过 40 字的总评，必须点出最致命的一点",
  "dimensions": [
    {"key": "与 rubric 完全一致的键", "score": 1到5的整数或null, "comment": "不超过 60 字", "evidence": "不超过 30 字的原话"}
  ],
  "questions": [
    {"index": 1, "question": "面试官的问题，不超过 30 字", "digest": "候选人回答的要点，不超过 50 字", "diagnosis": "问题出在哪，不超过 60 字", "rewrite": "示范改法，60–100 字，可直接照说", "model_answer": "这道题的完整参考回答，120–200 字，第一人称口语，可直接背", "score": 1到5的整数,
     "fu": [{"q": "这一层追问问了什么，不超过 30 字", "a": "他怎么答的，不超过 40 字", "verdict": "这一层暴露了什么，不超过 40 字"}]}
  ],
  "weakest": {"index": 1, "why": "不超过 50 字", "reprobe": "重放时会问的那一句追问，不超过 40 字"},
  "focus": ["下一轮训练重点一，不超过 25 字", "重点二", "重点三"],
  "drills": [{"title": "不超过 10 字", "how": "怎么练，不超过 60 字"}],
  "language": ${en
    ? '{"note": "整场英语表现，不超过 60 字", "fixes": [{"said": "他的原话片段", "better": "更准确或更地道的说法", "why": "错在哪，不超过 20 字"}], "oral": "口语层面的观察：语速、连贯、停顿、清晰度，不超过 60 字；没有语音就写空字符串"}'
    : 'null'}
}
dimensions 必须正好 ${dims.length} 项，键依次为：${keys}。
questions 必须覆盖全部 ${mainQs} 道题，index 从 1 开始连续；每题的 fu 按追问发生的顺序排列，次数必须和对话记录里该题的追问次数一致。${en ? '\nlanguage.fixes 给 3–6 条，只挑真的错或明显不地道的，不要把他正确的说法也改一遍。' : '\nlanguage 字段固定输出 null。'}`;
}

/* ---------------- 重放训练 ---------------- */
function buildDrillSystem(cfg, weakest) {
  const r = ROUNDS[cfg.round] || ROUNDS.behavioral;
  const langNote = r.lang === 'en' ? '\n5. 继续用英语提问。' : '';
  const bg = (cfg.background || '').trim();
  const bgNote = bg ? `\n【手头材料（节选）】\n${bg.slice(0, 600)}\n重放时照样扣在材料的具体细节上，不要退回通用题。\n` : '';
  return `你是同一位面试官（${cfg.persona}，压力档：${(PRESSURES[cfg.pressure] || PRESSURES.standard).label}），现在只做一件事：把刚才那道没答好的题重新问一遍。
${bgNote}
【原问题】
${weakest.question}
【上次的问题】
${weakest.why}
【上次的追问】
${weakest.reprobe || ''}

规则：
1. 第一句话就把原问题原样（或更短更狠地）再问一次，可以加半句压力，但不解释、不提示、不教学、不评价上次的回答。
2. 对方回答后，只针对上次那个薄弱点追问一次，不超过 90 字。
3. 全程面试官身份，不用 markdown、不写旁白、不加前缀、不一次问两件事。
4. 这是${r.label}，标准不变。${langNote}`;
}

function buildDrillJudgePrompt(cfg, weakest, before, after) {
  return `对比同一位候选人对同一道题的两次回答，判断有没有实质进步。

【问题】${weakest.question}
【第一次回答（较弱）】${before}
【第二次回答（重放）】${after}
【上次指出的问题】${weakest.why}

只输出 JSON，中文，不要 markdown：
{"before": 1到5的整数, "after": 1到5的整数, "improved": ["具体改好了什么，不超过 25 字", "…"], "still": ["仍然缺什么，不超过 25 字", "…"], "one_line": "不超过 40 字的判断"}
评分标准：证据具体、数字有归因、边界清楚才算进步；只是话说得更漂亮不算。`;
}
