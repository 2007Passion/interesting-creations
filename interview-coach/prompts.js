/* 返回 null 表示这题值得问；否则给出一条能直接用来纠偏的理由 */
function askValueOf(text) {
  const q = String(text || '').replace(/\s+/g, ' ').trim();
  if (!q) return null;
  const en = /^[\x00-\x7F\s]*$/.test(q) || /^(when|what|which|where|how|do|did|have|can|could|why|who)\b/i.test(q);
  const rules = en ? EN_ASK_RULES : ASK_RULES;
  for (let i = 0; i < rules.length; i++) {
    const r = rules[i];
    if (!r.hit.test(q)) continue;
    if (r.keep && r.keep.test(q)) continue;
    return { tag: r.tag, label: r.label, fix: r.fix };
  }
  return null;
}

